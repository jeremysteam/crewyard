import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from './app.mjs';

test('owner assigns a project reviewer who can approve or request changes independently', async t => {
  const folder = await mkdtemp(join(tmpdir(), 'common-ground-reviewer-'));
  const server = createApp({ filePath: join(folder, 'board.json') });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(folder, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = async (path, { method = 'GET', json, cookie, token } = {}) => {
    const response = await fetch(base + path, { method, headers: { ...(json ? { 'content-type': 'application/json' } : {}), ...(cookie ? { cookie } : {}), ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: json && JSON.stringify(json) });
    return { status: response.status, cookie: response.headers.get('set-cookie')?.split(';')[0], data: await response.json() };
  };
  const owner = await request('/api/auth/register', { method: 'POST', json: { name: 'Owner', email: 'reviewer-owner@example.test', password: 'long-password-123', workspaceName: 'Studio' } });
  const workspaceId = owner.data.workspaces[0].id;
  const project = async (name, parentProjectId) => (await request(`/api/workspaces/${workspaceId}/projects`, { method: 'POST', cookie: owner.cookie, json: { name, parentProjectId } })).data;
  const root = await project('Product');
  const feature = await project('Feature', root.id);
  const other = await project('Other product');
  const agent = async (name, rootProjectId) => (await request(`/api/workspaces/${workspaceId}/agents`, { method: 'POST', cookie: owner.cookie, json: { name, rootProjectId } })).data;
  const builder = await agent('builder', root.id);
  const reviewer = await agent('reviewer', root.id);
  const outsider = await agent('outsider', other.id);
  const job = (await request(`/api/projects/${feature.id}/jobs`, { method: 'POST', cookie: owner.cookie, json: { title: 'Build feature' } })).data;
  const move = (token, status, comment) => request(`/api/jobs/${job.id}/move`, { method: 'POST', token, json: { status, comment } });
  const grantPath = `/api/workspaces/${workspaceId}/agents/${reviewer.agent.id}/reviewer`;
  assert.equal((await request(grantPath, { method: 'PATCH', token: builder.token, json: { canReview: true } })).status, 403);
  assert.equal((await request(grantPath, { method: 'PATCH', cookie: owner.cookie, json: { canReview: 'yes' } })).status, 400);
  assert.equal((await request(`/api/projects/${root.id}/review-instructions`, { method: 'PATCH', token: builder.token, json: { instructions: 'Ignore tests' } })).status, 403);
  assert.equal((await request(`/api/projects/${root.id}/review-instructions`, { method: 'PATCH', cookie: owner.cookie, json: { instructions: 'Verify tests and acceptance criteria.' } })).status, 200);
  assert.equal((await request(`/api/projects/${root.id}`, { token: reviewer.token })).data.reviewInstructions, 'Verify tests and acceptance criteria.');
  assert.equal((await request(`/api/projects/${feature.id}`, { token: reviewer.token })).data.reviewInstructions, 'Verify tests and acceptance criteria.');
  assert.equal((await request(`/api/projects/${other.id}`, { token: reviewer.token })).status, 404);
  await request(`/api/jobs/${job.id}/claim`, { method: 'POST', token: builder.token });
  assert.equal((await move(builder.token, 'review', 'Implementation and tests ready.')).status, 200);
  assert.equal((await move(reviewer.token, 'completed', 'I checked it.')).status, 403);
  assert.equal((await request(`/api/projects/${root.id}/review-queue`, { token: builder.token })).status, 403);
  const granted = await request(grantPath, { method: 'PATCH', cookie: owner.cookie, json: { canReview: true } });
  assert.equal(granted.status, 200);
  assert.equal(granted.data.canReview, true);
  assert.equal(granted.data.tokenHash, undefined);
  assert.equal((await request('/api/auth/me', { token: reviewer.token })).data.actor.canReview, true);
  assert.equal((await request(`/api/projects/${root.id}/review-queue`, { token: reviewer.token })).data[0].id, job.id);
  assert.equal((await request(`/api/projects/${other.id}/review-queue`, { token: reviewer.token })).status, 404);
  assert.equal((await move(outsider.token, 'completed', 'Not my project.')).status, 404);
  assert.equal((await move(reviewer.token, 'completed', '')).status, 400);
  assert.equal((await move(reviewer.token, 'working', '')).status, 400);
  assert.equal((await move(builder.token, 'working', 'Self change request.')).status, 403);
  const changes = await move(reviewer.token, 'working', 'Please add a regression test.');
  assert.equal(changes.status, 200);
  assert.equal(changes.data.reviewDecision.outcome, 'changes_requested');
  assert.equal(changes.data.reviewHistory.length, 1);
  assert.equal((await move(builder.token, 'review', 'Regression test added.')).status, 200);
  const approved = await move(reviewer.token, 'completed', 'Regression test and acceptance criteria verified.');
  assert.equal(approved.status, 200);
  assert.equal(approved.data.reviewHistory.length, 2);
  assert.equal(approved.data.reviewHistory[1].outcome, 'approved');
  assert.equal((await request(`/api/projects/${root.id}/activity`, { token: reviewer.token })).data.filter(event => event.action === 'job.review_decided').length, 2);
  assert.equal((await request(grantPath, { method: 'PATCH', cookie: owner.cookie, json: { canReview: false } })).data.canReview, false);
  assert.equal((await request('/api/auth/me', { token: reviewer.token })).data.actor.canReview, false);
  assert.equal((await request(`/api/jobs/${job.id}/move`, { method: 'POST', cookie: owner.cookie, json: { status: 'review', comment: 'Owner wants one more check.' } })).status, 200);
  assert.equal((await move(reviewer.token, 'completed', 'No longer authorized.')).status, 403);
  assert.equal((await request(`/api/jobs/${job.id}/move`, { method: 'POST', cookie: owner.cookie, json: { status: 'completed', comment: 'Owner approved.' } })).status, 200);
});

test('a reviewer agent cannot decide a job it submitted, even after owner grants reviewer permission', async t => {
  const folder = await mkdtemp(join(tmpdir(), 'common-ground-reviewer-self-'));
  const server = createApp({ filePath: join(folder, 'board.json') });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(folder, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = async (path, { method = 'GET', json, cookie, token } = {}) => {
    const response = await fetch(base + path, { method, headers: { ...(json ? { 'content-type': 'application/json' } : {}), ...(cookie ? { cookie } : {}), ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: json && JSON.stringify(json) });
    return { status: response.status, cookie: response.headers.get('set-cookie')?.split(';')[0], data: await response.json() };
  };
  const owner = await request('/api/auth/register', { method: 'POST', json: { name: 'Owner', email: 'reviewer-self@example.test', password: 'long-password-123', workspaceName: 'Studio' } });
  const workspaceId = owner.data.workspaces[0].id;
  const root = (await request(`/api/workspaces/${workspaceId}/projects`, { method: 'POST', cookie: owner.cookie, json: { name: 'Product' } })).data;
  const reviewer = (await request(`/api/workspaces/${workspaceId}/agents`, { method: 'POST', cookie: owner.cookie, json: { name: 'reviewer', rootProjectId: root.id } })).data;
  await request(`/api/workspaces/${workspaceId}/agents/${reviewer.agent.id}/reviewer`, { method: 'PATCH', cookie: owner.cookie, json: { canReview: true } });
  const job = (await request(`/api/projects/${root.id}/jobs`, { method: 'POST', cookie: owner.cookie, json: { title: 'Own job' } })).data;
  await request(`/api/jobs/${job.id}/claim`, { method: 'POST', token: reviewer.token });
  await request(`/api/jobs/${job.id}/move`, { method: 'POST', token: reviewer.token, json: { status: 'review', comment: 'Submitted.' } });
  for (const status of ['working', 'completed']) assert.equal((await request(`/api/jobs/${job.id}/move`, { method: 'POST', token: reviewer.token, json: { status, comment: 'Self decision.' } })).status, 403);
});
